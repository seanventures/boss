#!/usr/bin/env bash
# layer1-runtime — Docker pools + external networks + platform-dns stub
set -euo pipefail
KIT="${GOLDENEYE_KIT_ROOT:-/opt/goldeneye}"
# shellcheck source=/dev/null
source "$KIT/lib/common.sh"
ge_require_root
ge_step "layer1-runtime"

command -v docker >/dev/null || ge_die "docker required (re-run kit install.sh)"

DATA_ROOT="$(ge_load_site_value paths.data_root)"
DATA_ROOT="${DATA_ROOT:-/data}"
mkdir -p "$DATA_ROOT/docker" /etc/docker

# daemon.json — address pools + log rotation (merge carefully if exists)
if [ ! -f /etc/docker/daemon.json ]; then
  cat >/etc/docker/daemon.json <<JSON
{
  "data-root": "${DATA_ROOT}/docker",
  "log-driver": "json-file",
  "log-opts": { "max-size": "10m", "max-file": "3" },
  "live-restore": true,
  "default-address-pools": [
    { "base": "10.100.0.0/16", "size": 20 }
  ]
}
JSON
  systemctl restart docker || true
else
  ge_info "daemon.json already present — not clobbering"
fi

for net in web storage ops; do
  docker network inspect "$net" >/dev/null 2>&1 || docker network create "$net"
  ge_info "network $net ready"
done

# platform-dns lightweight recipe (optional container)
DNS_DIR="$KIT/packages/layer1-runtime/platform-dns"
if [ -f "$DNS_DIR/compose.yaml" ]; then
  PUBLIC_IP="$(ge_load_site_value network.public_ip)"
  TN_IP="$(ge_load_site_value network.tailnet_ip)"
  if [ -z "$TN_IP" ] && command -v tailscale >/dev/null 2>&1; then
    TN_IP="$(tailscale ip -4 2>/dev/null | head -1 || true)"
  fi
  PUBLIC_DOMAIN="$(ge_load_site_value dns.public_domain)"
  LOCAL_DOMAIN="$(ge_load_site_value dns.local_domain)"
  mkdir -p /opt/goldeneye/run/platform-dns
  cat >/opt/goldeneye/run/platform-dns/dnsmasq.conf <<EOF
# generated by layer1-runtime
no-resolv
server=1.1.1.1
server=8.8.8.8
$( [ -n "$PUBLIC_IP" ] && [ -n "$PUBLIC_DOMAIN" ] && echo "address=/${PUBLIC_DOMAIN}/${PUBLIC_IP}" )
$( [ -n "$TN_IP" ] && [ -n "$LOCAL_DOMAIN" ] && echo "address=/${LOCAL_DOMAIN}/${TN_IP}" )
EOF
  ( cd "$DNS_DIR" && docker compose -p platform-dns up -d ) || ge_info "platform-dns compose skipped"
fi

ge_info "layer1-runtime complete"
