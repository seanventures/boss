/**
 * Regenerates lib/identity/read-routes.gen.ts from the API's role matrix (tests/identity/matrix.yaml,
 * itself generated from the routing table): every GET /v1 route and the permission it checks.
 *
 *   node apps/web/scripts/read-routes.mjs          (from the repo root, or apps/web)
 *
 * tests/a-page-fetches-only-what-the-viewer-may-read.test.ts refuses a stale copy.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WEB = join(dirname(fileURLToPath(import.meta.url)), "..");

export function readRoutesSource(matrix) {
  const rows = [];
  for (const line of matrix.split("\n")) {
    const m = /^"GET (\/v1\/\S+)": \["permit ([a-z_]+:[a-z_]+) @ /.exec(line);
    if (!m || /\{[^}]*:path\}/.test(m[1])) continue;
    // Stored without the "/v1/" prefix: this is a table, not a caller, and the console's source
    // scanners (writing GETs, start doors) read "/v1/…" literals as calls.
    rows.push([m[1].replace(/\{[^}]*\}/g, "{}").slice("/v1/".length), m[2]]);
  }
  rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const body = rows.map(([p, perm]) => `  [${JSON.stringify(p)}, ${JSON.stringify(perm)}],`).join("\n");
  return `// GENERATED by apps/web/scripts/read-routes.mjs from tests/identity/matrix.yaml. Do not edit.
//
// Every GET /v1 route the API declares with a permission, and that permission (the path after
// "/v1/"; "{}" is one path segment). lib/identity/read-gates.ts reads it to keep the browser from asking for what the
// viewer may not read.
import type { Permission } from "./permissions.gen";

export const READ_ROUTES: ReadonlyArray<readonly [string, Permission]> = [
${body}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const matrix = readFileSync(join(WEB, "..", "..", "tests/identity/matrix.yaml"), "utf8");
  writeFileSync(join(WEB, "lib/identity/read-routes.gen.ts"), readRoutesSource(matrix));
}
