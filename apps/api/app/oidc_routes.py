"""BOSS as an OpenID Connect provider for the apps it builds (F6).

Spec: docs/product/APP_TEMPLATES_AND_SECURITY_LOOP.md §6.2 (protocol) and §6.5 (admin API).
Owner: stream S6.

DAY-1 INTERFACE (stream S0): every route is declared and answers 501 `not_implemented_yet` until
S6 builds it.

- Protocol endpoints live under the issuer, `/oidc/{org_slug}`. They are public by necessity:
  discovery and the JWKS publish nothing secret (`jwks`); the rest are
  `oidc_provider_endpoint` (IDENTITY_BUILD.md §7, AP-2): each authenticates by what the protocol
  says, never by a BOSS credential: `authorize` by the app session (customer pool) or the console
  session plus `oidc_app:sign_in` (workforce pool), with PKCE S256 always; `token` and
  `revocation` by client authentication; `userinfo` by an app access token. An OIDC token is never
  accepted by BOSS's own verifiers, and a BOSS token is never accepted here (`typ` separation).
- ID tokens are RS256 by default, EdDSA opt-in per client (D10; IDENTITY.md D35).
- Admin routes (`/v1/oidc/*`) are ordinary permitted routes. Client secrets are generated by
  BOSS, shown once, and otherwise returned as presence only.
"""
from __future__ import annotations

from typing import Any

from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse

from boss_engine.identity import P, PublicReason, Scope, permit, public

SPEC = "APP_TEMPLATES_AND_SECURITY_LOOP.md §6"


def not_implemented_yet() -> JSONResponse:
    return JSONResponse({"error": "not_implemented_yet", "owner": "S6", "spec": SPEC}, status_code=501)


def verify_oidc_request(request: Request) -> Any:
    """The verifier every `oidc_provider_endpoint` route names (§6.2): client authentication
    (client_secret_basic or private_key_jwt against the client's inline JWKS), PKCE S256, exact
    redirect_uri match, and the app session or app access token. S6 implements it; until then
    every protocol route answers 501 and authenticates nothing."""
    raise NotImplementedError("S6: the OIDC protocol verifier")


def build_oidc_router() -> APIRouter:
    router = APIRouter(tags=["oidc"])
    OP = PublicReason.OIDC_PROVIDER_ENDPOINT

    # ---- protocol (§6.2), issuer https://<BOSS_PUBLIC_URL>/oidc/<org_slug> -----------------------
    @router.get("/oidc/{org_slug}/.well-known/openid-configuration")
    @public(reason=PublicReason.JWKS)
    def discovery(org_slug: str) -> JSONResponse:
        return not_implemented_yet()

    @router.get("/oidc/{org_slug}/jwks")
    @public(reason=PublicReason.JWKS)
    def jwks(org_slug: str) -> JSONResponse:
        return not_implemented_yet()

    # Authorization code flow only, PKCE S256 required for every client.
    @router.api_route("/oidc/{org_slug}/authorize", methods=["GET", "POST"])
    @public(reason=OP, verifier=verify_oidc_request)
    def authorize(org_slug: str) -> JSONResponse:
        return not_implemented_yet()

    @router.post("/oidc/{org_slug}/token")
    @public(reason=OP, verifier=verify_oidc_request)
    def token(org_slug: str) -> JSONResponse:
        return not_implemented_yet()

    @router.api_route("/oidc/{org_slug}/userinfo", methods=["GET", "POST"])
    @public(reason=OP, verifier=verify_oidc_request)
    def userinfo(org_slug: str) -> JSONResponse:
        return not_implemented_yet()

    @router.post("/oidc/{org_slug}/revocation")
    @public(reason=OP, verifier=verify_oidc_request)
    def revocation(org_slug: str) -> JSONResponse:
        return not_implemented_yet()

    # RP-initiated logout; post_logout_redirect_uri is an exact match.
    @router.api_route("/oidc/{org_slug}/end_session", methods=["GET", "POST"])
    @public(reason=OP, verifier=verify_oidc_request)
    def end_session(org_slug: str) -> JSONResponse:
        return not_implemented_yet()

    # ---- admin: pools (§6.5) -------------------------------------------------------------------
    @router.get("/v1/oidc/pools")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def list_pools() -> JSONResponse:
        return not_implemented_yet()

    @router.post("/v1/oidc/pools")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def create_pool() -> JSONResponse:
        return not_implemented_yet()

    @router.get("/v1/oidc/pools/{pool_id}")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def get_pool(pool_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.patch("/v1/oidc/pools/{pool_id}")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def update_pool(pool_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.delete("/v1/oidc/pools/{pool_id}")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def delete_pool(pool_id: str) -> JSONResponse:
        return not_implemented_yet()

    # ---- admin: a pool's users (customer pools) --------------------------------------------------
    @router.get("/v1/oidc/pools/{pool_id}/users")
    @permit(P.OIDC_POOL_USER_MANAGE, scope=Scope.org())
    def list_pool_users(pool_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.post("/v1/oidc/pools/{pool_id}/users")
    @permit(P.OIDC_POOL_USER_MANAGE, scope=Scope.org())
    def invite_pool_user(pool_id: str) -> JSONResponse:
        return not_implemented_yet()

    # Disable / enable, reset MFA.
    @router.patch("/v1/oidc/pools/{pool_id}/users/{user_id}")
    @permit(P.OIDC_POOL_USER_MANAGE, scope=Scope.org())
    def update_pool_user(pool_id: str, user_id: str) -> JSONResponse:
        return not_implemented_yet()

    # ---- admin: clients (Admins everywhere; app owners on their project) -------------------------
    @router.get("/v1/oidc/clients")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.project_or_org(query="project_id"))
    def list_clients() -> JSONResponse:
        return not_implemented_yet()

    @router.post("/v1/oidc/clients")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.project(body="project_id"))
    def create_client() -> JSONResponse:
        return not_implemented_yet()

    @router.get("/v1/oidc/clients/{client_id}")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def get_client(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.patch("/v1/oidc/clients/{client_id}")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def update_client(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.delete("/v1/oidc/clients/{client_id}")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def delete_client(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.post("/v1/oidc/clients/{client_id}/rotate-secret")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def rotate_client_secret(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    # ---- admin: a client's app roles and their assignments --------------------------------------
    @router.get("/v1/oidc/clients/{client_id}/roles")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def list_client_roles(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.post("/v1/oidc/clients/{client_id}/roles")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def create_client_role(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.get("/v1/oidc/clients/{client_id}/role-assignments")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def list_role_assignments(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    @router.post("/v1/oidc/clients/{client_id}/role-assignments")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def assign_client_role(client_id: str) -> JSONResponse:
        return not_implemented_yet()

    # ---- admin: consents -----------------------------------------------------------------------
    @router.get("/v1/oidc/consents")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def list_consents() -> JSONResponse:
        return not_implemented_yet()

    @router.post("/v1/oidc/consents/revoke")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def revoke_consent() -> JSONResponse:
        return not_implemented_yet()

    return router
