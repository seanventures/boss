def _first_party_allowed(ctx: Any, db: Any) -> bool:
    """`first_party` skips consent: only an admin of app sign-in may set it (S6.7)."""
    from boss_engine.identity import authz
    from boss_engine.identity.scope import ResolvedScope

    return authz.check(ctx, P.OIDC_ADMIN, ResolvedScope.org_level(ctx.principal.org_id), db=db).allowed


def _client_of(db: Any, ctx: Any, client_id: str) -> dict[str, Any]:
    c = oidc_clients.load(db, org_id=ctx.principal.org_id, client_id=client_id, any_status=True)
    if c is None or c["status"] == "deleted":
        raise LookupError("not_found")
    return c


def build_oidc_router() -> APIRouter:
    router = APIRouter(tags=["oidc"])
    OP = PublicReason.OIDC_PROVIDER_ENDPOINT

    # ---- protocol (§6.2), issuer https://<BOSS_PUBLIC_URL>/oidc/<org_slug> -----------------------
    @router.get("/oidc/{org_slug}/.well-known/openid-configuration")
    @public(reason=PublicReason.JWKS)
    async def discovery(org_slug: str) -> Response:
        return await _run(lambda db: protocol.discovery(db, org_slug))

    @router.get("/oidc/{org_slug}/jwks")
    @public(reason=PublicReason.JWKS)
    async def jwks(org_slug: str) -> Response:
        return await _run(lambda db: protocol.jwks(db, org_slug))

    # Authorization code flow only, PKCE S256 required for every client.
    @router.api_route("/oidc/{org_slug}/authorize", methods=["GET", "POST"])
    @public(reason=OP, verifier=verify_oidc_request)
    async def authorize(org_slug: str, request: Request) -> Response:
        form = await _form(request)
        if form is None:
            return _too_large()
        pairs = form if request.method.upper() == "POST" else _query(request)
        browser = _browser(request)
        return await _run(lambda db: protocol.authorize(db, org_slug, pairs, browser))

    # Back from the console sign-in with the pending request (single use).
    @router.get("/oidc/{org_slug}/resume")
    @public(reason=OP, verifier=verify_oidc_request)
    async def resume(org_slug: str, request: Request) -> Response:
        pairs, browser = _query(request), _browser(request)
        return await _run(lambda db: protocol.resume(db, org_slug, pairs, browser))

    # The hosted consent form's POST (session + Origin + session-bound token).
    @router.post("/oidc/{org_slug}/consent")
    @public(reason=OP, verifier=verify_oidc_request)
    async def consent(org_slug: str, request: Request) -> Response:
        form = await _form(request)
        if form is None:
            return _too_large()
        browser = _browser(request)
        return await _run(lambda db: protocol.consent_submit(db, org_slug, form, browser))

    # The hosted pages (customer pools; workforce re-authentication): a view, and the steps.
    @router.get("/oidc/{org_slug}/account")
    @public(reason=OP, verifier=verify_oidc_request)
    async def account(org_slug: str, request: Request) -> Response:
        params, browser = dict(_query(request)), _browser(request)

        def call(db: Any) -> protocol.Reply:
            try:
                org_id, _, _ = protocol.resolve(db, org_slug)
            except Exception:  # noqa: BLE001
                return protocol.discovery(db, org_slug)   # the same 404/503 answer
            return hosted.view(db, org_id, params, browser)
        return await _run(call)

    @router.post("/oidc/{org_slug}/hosted/{step}")
    @public(reason=OP, verifier=verify_oidc_request)
    async def hosted_step(org_slug: str, step: str, request: Request) -> Response:
        browser = _browser(request)
        if (browser.content_type or "").startswith("application/json"):
            raw = await request.body()
            if len(raw) > MAX_BODY:
                return _too_large()
            try:
                params = json.loads(raw or b"{}")
            except ValueError:
                params = None
            if not isinstance(params, dict):
                return JSONResponse({"error": "invalid_request"}, status_code=400)
        else:
            form = await _form(request)
            if form is None:
                return _too_large()
            params, seen = {}, set()
            for k, v in form:
                if k in seen:
                    return JSONResponse({"error": "invalid_request"}, status_code=400)
                seen.add(k)
                params[k] = v
        return await _run(lambda db: hosted.step(db, org_slug, step, params, browser))

    @router.post("/oidc/{org_slug}/token")
    @public(reason=OP, verifier=verify_oidc_request)
    async def token(org_slug: str, request: Request) -> Response:
        form = await _form(request)
        if form is None:
            return _too_large()
        headers = {k.lower(): v for k, v in request.headers.items()}
        ip = _browser(request).ip
        return await _run(lambda db: protocol.token(db, org_slug, form, headers, ip))

    @router.api_route("/oidc/{org_slug}/userinfo", methods=["GET", "POST"])
    @public(reason=OP, verifier=verify_oidc_request)
    async def userinfo(org_slug: str, request: Request) -> Response:
        form = await _form(request)
        if form is None:
            return _too_large()
        headers = {k.lower(): v for k, v in request.headers.items()}
        query, method = _query(request), request.method
        return await _run(lambda db: protocol.userinfo(db, org_slug, method=method, headers=headers,
                                                       query=query, form=form))

    @router.post("/oidc/{org_slug}/revocation")
    @public(reason=OP, verifier=verify_oidc_request)
    async def revocation(org_slug: str, request: Request) -> Response:
        form = await _form(request)
        if form is None:
            return _too_large()
        headers = {k.lower(): v for k, v in request.headers.items()}
        ip = _browser(request).ip
        return await _run(lambda db: protocol.revocation(db, org_slug, form, headers, ip))

    # RP-initiated logout; post_logout_redirect_uri is an exact match.
    @router.api_route("/oidc/{org_slug}/end_session", methods=["GET", "POST"])
    @public(reason=OP, verifier=verify_oidc_request)
    async def end_session(org_slug: str, request: Request) -> Response:
        form = await _form(request)
        if form is None:
            return _too_large()
        pairs = form if request.method.upper() == "POST" else _query(request)
        browser = _browser(request)
        return await _run(lambda db: protocol.end_session(db, org_slug, pairs, browser))

    # ---- admin: pools (§6.5) -------------------------------------------------------------------
    @router.get("/v1/oidc/pools")
    @permit(P.OIDC_READ, scope=Scope.org())
    def list_pools(request: Request) -> JSONResponse:
        return _admin(request, lambda db, ctx: {"pools": [oidc_pools.public_view(p) for p in
                                                          oidc_pools.list_pools(db, org_id=ctx.principal.org_id)]})

    @router.post("/v1/oidc/pools")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def create_pool(request: Request, body: PoolBody) -> JSONResponse:
        return _admin(request, lambda db, ctx: oidc_pools.public_view(oidc_pools.create(
            db, org_id=ctx.principal.org_id, actor=ctx.principal.id, body=body.model_dump(exclude_none=True))), 201)

    @router.get("/v1/oidc/pools/{pool_id}")
    @permit(P.OIDC_READ, scope=Scope.org())
    def get_pool(pool_id: str, request: Request) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            p = oidc_pools.load(db, org_id=ctx.principal.org_id, pool_id=pool_id)
            if p is None:
                raise LookupError("not_found")
            return oidc_pools.public_view(p)
        return _admin(request, fn)

    @router.patch("/v1/oidc/pools/{pool_id}")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def update_pool(pool_id: str, request: Request, body: PoolBody) -> JSONResponse:
        return _admin(request, lambda db, ctx: oidc_pools.public_view(oidc_pools.update(
            db, org_id=ctx.principal.org_id, actor=ctx.principal.id, pool_id=pool_id,
            body=body.model_dump(exclude_none=True))))

    @router.delete("/v1/oidc/pools/{pool_id}")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def delete_pool(pool_id: str, request: Request) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            oidc_pools.delete(db, org_id=ctx.principal.org_id, actor=ctx.principal.id, pool_id=pool_id)
            return {"deleted": pool_id}
        return _admin(request, fn)

    # ---- admin: a pool's users (customer pools) ------------------------------------------------
    def _customer_pool(db: Any, ctx: Any, pool_id: str) -> dict[str, Any]:
        pool = oidc_pools.load(db, org_id=ctx.principal.org_id, pool_id=pool_id)
        if pool is None or pool["kind"] != "customer":
            raise LookupError("not_found")
        return pool

    @router.get("/v1/oidc/pools/{pool_id}/users")
    @permit(P.OIDC_READ, scope=Scope.org())
    def list_pool_users(pool_id: str, request: Request) -> JSONResponse:
        return _admin(request, lambda db, ctx: {"users": oidc_customers.list_users(
            db, pool_id=_customer_pool(db, ctx, pool_id)["id"])})

    @router.post("/v1/oidc/pools/{pool_id}/users")
    @permit(P.OIDC_POOL_USER_MANAGE, scope=Scope.org())
    def invite_pool_user(pool_id: str, request: Request, body: PoolUserBody) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            from boss_engine.identity.authn_support import public_origin

            pool = _customer_pool(db, ctx, pool_id)
            if not body.email:
                raise ValueError("email is required")
            url = f"{public_origin(db, ctx.principal.org_id)}/oidc/{ctx.principal.org_id}/account?pool={pool['id']}"
            return oidc_customers.invite(db, org_id=ctx.principal.org_id, actor=ctx.principal.id, pool=pool,
                                         email=body.email, name=body.name, account_url=url)
        return _admin(request, fn, 201)

    # Disable / enable, reset MFA.
    @router.patch("/v1/oidc/pools/{pool_id}/users/{user_id}")
    @permit(P.OIDC_POOL_USER_MANAGE, scope=Scope.org())
    def update_pool_user(pool_id: str, user_id: str, request: Request, body: PoolUserBody) -> JSONResponse:
        return _admin(request, lambda db, ctx: oidc_customers.admin_update(
            db, org_id=ctx.principal.org_id, actor=ctx.principal.id, pool=_customer_pool(db, ctx, pool_id),
            user_id=user_id, status=body.status, reset_mfa=bool(body.reset_mfa), name=body.name))

    # ---- admin: clients (Admins everywhere; app owners on their project) -------------------------
    @router.get("/v1/oidc/clients")
    @permit(P.OIDC_READ, scope=Scope.org())
    def list_clients(request: Request, project_id: Optional[str] = None) -> JSONResponse:
        return _admin(request, lambda db, ctx: {"clients": [oidc_clients.public_view(c) for c in oidc_clients.list_clients(
            db, org_id=ctx.principal.org_id, project_id=project_id)]})

    @router.post("/v1/oidc/clients")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.project(body="project_id"))
    def create_client(request: Request, body: ClientBody) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            data = body.model_dump(exclude_none=True)
            data.pop("status", None)
            if data.get("first_party") and not _first_party_allowed(ctx, db):
                raise PermissionError("only an app sign-in admin may mark a client first-party")
            client, secret = oidc_clients.create(db, org_id=ctx.principal.org_id, actor=ctx.principal.id, body=data)
            out = oidc_clients.public_view(client)
            if secret is not None:
                out["client_secret"] = secret       # shown once; never readable again
            return out
        return _admin(request, fn, 201)

    @router.get("/v1/oidc/clients/{client_id}")
    @permit(P.OIDC_READ, scope=Scope.org())
    def get_client(client_id: str, request: Request) -> JSONResponse:
        return _admin(request, lambda db, ctx: oidc_clients.public_view(_client_of(db, ctx, client_id)))

    @router.patch("/v1/oidc/clients/{client_id}")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def update_client(client_id: str, request: Request, body: ClientBody) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            data = body.model_dump(exclude_none=True)
            for fixed in ("project_id", "app_key", "pool_id", "type", "token_endpoint_auth_method"):
                if fixed in data:
                    raise ValueError(f"{fixed} cannot change; register a new client")
            current = _client_of(db, ctx, client_id)
            if "first_party" in data and data["first_party"] != current["first_party"] and \
                    not _first_party_allowed(ctx, db):
                raise PermissionError("only an app sign-in admin may change first-party")
            return oidc_clients.public_view(oidc_clients.update(
                db, org_id=ctx.principal.org_id, actor=ctx.principal.id, client_id=client_id, body=data))
        return _admin(request, fn)

    @router.delete("/v1/oidc/clients/{client_id}")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def delete_client(client_id: str, request: Request) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            oidc_clients.delete(db, org_id=ctx.principal.org_id, actor=ctx.principal.id, client_id=client_id)
            return {"deleted": client_id}
        return _admin(request, fn)

    @router.post("/v1/oidc/clients/{client_id}/rotate-secret")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def rotate_client_secret(client_id: str, request: Request) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            client, secret = oidc_clients.rotate_secret(db, org_id=ctx.principal.org_id, actor=ctx.principal.id,
                                                        client_id=client_id)
            return {**oidc_clients.public_view(client), "client_secret": secret}
        return _admin(request, fn)

    # ---- admin: a client's app roles and their assignments --------------------------------------
    @router.get("/v1/oidc/clients/{client_id}/roles")
    @permit(P.OIDC_READ, scope=Scope.org())
    def list_client_roles(client_id: str, request: Request) -> JSONResponse:
        return _admin(request, lambda db, ctx: {"roles": oidc_pools.list_roles(db, client=_client_of(db, ctx, client_id))})

    @router.post("/v1/oidc/clients/{client_id}/roles")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def create_client_role(client_id: str, request: Request, body: RoleBody) -> JSONResponse:
        return _admin(request, lambda db, ctx: oidc_pools.create_role(
            db, actor=ctx.principal.id, client=_client_of(db, ctx, client_id), role_key=body.role_key,
            name=body.name or body.role_key), 201)

    @router.get("/v1/oidc/clients/{client_id}/role-assignments")
    @permit(P.OIDC_READ, scope=Scope.org())
    def list_role_assignments(client_id: str, request: Request) -> JSONResponse:
        return _admin(request, lambda db, ctx: {"assignments": oidc_pools.list_assignments(
            db, client=_client_of(db, ctx, client_id))})

    @router.post("/v1/oidc/clients/{client_id}/role-assignments")
    @permit(P.OIDC_CLIENT_MANAGE, scope=Scope.of("oidc_client", path="client_id"))
    def assign_client_role(client_id: str, request: Request, body: AssignmentBody) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            oidc_pools.assign_role(db, actor=ctx.principal.id, client=_client_of(db, ctx, client_id),
                                   subject_ref=body.subject_ref, role_key=body.role_key, remove=body.remove)
            return {"subject_ref": body.subject_ref, "role_key": body.role_key, "assigned": not body.remove}
        return _admin(request, fn)

    # ---- admin: consents -----------------------------------------------------------------------
    @router.get("/v1/oidc/consents")
    @permit(P.OIDC_READ, scope=Scope.org())
    def list_consents(request: Request, client_id: Optional[str] = None) -> JSONResponse:
        return _admin(request, lambda db, ctx: {"consents": oidc_consent.list_consents(
            db, org_id=ctx.principal.org_id, client_id=client_id)})

    @router.post("/v1/oidc/consents/revoke")
    @permit(P.OIDC_ADMIN, scope=Scope.org())
    def revoke_consent(request: Request, body: ConsentRevokeBody) -> JSONResponse:
        def fn(db: Any, ctx: Any) -> Any:
            if not oidc_consent.revoke(db, org_id=ctx.principal.org_id, client_id=body.client_id,
                                       subject_ref=body.subject_ref, actor=ctx.principal.id):
                raise LookupError("no such consent")
            return {"revoked": True}
        return _admin(request, fn)

    return router
