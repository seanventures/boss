SPEC = "APP_TEMPLATES_AND_SECURITY_LOOP.md §6"
MAX_BODY = 64 * 1024


def not_implemented_yet() -> JSONResponse:
    return JSONResponse({"error": "not_implemented_yet", "owner": "S6", "spec": SPEC}, status_code=501)


def verify_oidc_request(request: Request) -> Any:
    """The verifier every `oidc_provider_endpoint` route names (§6.2). The checks live in
    boss_engine.oidc_provider: client authentication (`clients.authenticate`: client_secret_basic
    or private_key_jwt against the client's inline JWKS), PKCE S256 and the exact redirect_uri
    (`protocol.authorize`, `tokens.redeem_code`), the console session plus `oidc_app:sign_in`
    (`protocol._proceed`), the consent form's session-bound token (`protocol.consent_submit`) and
    the app access token (`protocol.userinfo`, `tokens.verify_own`)."""
    return protocol


# ---- request plumbing ----------------------------------------------------------------------------

def _browser(request: Request) -> protocol.Browser:
    from boss_engine.identity import authn

    from .routers.identity_auth import credentials

    from boss_engine.oidc_provider import customers

    return protocol.Browser(
        session_cookie=request.cookies.get(authn.SESSION_COOKIE), ip=authn.client_ip_of(credentials(request)),
        user_agent=(request.headers.get("user-agent") or "")[:400] or None,
        origin=request.headers.get("origin"), sec_fetch_site=request.headers.get("sec-fetch-site"),
        app_session=request.cookies.get(customers.APP_SESSION_COOKIE),
        app_preauth=request.cookies.get(customers.APP_PREAUTH_COOKIE),
        content_type=(request.headers.get("content-type") or "").lower() or None)


async def _form(request: Request) -> Optional[list[tuple[str, str]]]:
    """The urlencoded body as pairs (duplicates kept, so the protocol can refuse them); None when
    it is too large."""
    if request.method.upper() not in ("POST", "PUT", "PATCH"):
        return []
    body = await request.body()
    if len(body) > MAX_BODY:
        return None
    ctype = (request.headers.get("content-type") or "").lower()
    if not ctype.startswith("application/x-www-form-urlencoded"):
        return []
    try:
        return parse_qsl(body.decode("utf-8"), keep_blank_values=True, strict_parsing=False, max_num_fields=100)
    except (UnicodeDecodeError, ValueError):
        return None


def _query(request: Request) -> list[tuple[str, str]]:
    try:
        return parse_qsl(request.url.query, keep_blank_values=True, max_num_fields=100)
    except ValueError:
        return [("", "")] * 2      # too many fields: a repeated (empty) parameter, refused as such


def _render(reply: protocol.Reply) -> Response:
    if isinstance(reply.body, dict):
        response: Response = JSONResponse(reply.body, status_code=reply.status, headers=reply.headers)
    elif isinstance(reply.body, str):
        response = HTMLResponse(reply.body, status_code=reply.status, headers=reply.headers)
    else:
        response = Response(status_code=reply.status, headers=reply.headers)
    for cookie in reply.cookies:
        response.raw_headers.append((b"set-cookie", cookie.encode("latin-1")))
    return response


async def _run(fn: Callable[[Any], protocol.Reply]) -> Response:
    def call() -> protocol.Reply:
        with begin() as db:
            return fn(db)
    return _render(await run_in_threadpool(call))


def _too_large() -> Response:
    return JSONResponse({"error": "invalid_request", "error_description": "request too large"}, status_code=413,
                        headers={"Cache-Control": "no-store"})


# ---- admin plumbing ------------------------------------------------------------------------------

def _ctx(request: Request) -> Any:
    from .routers.identity_auth import current_context

    return current_context(request)


def _admin(request: Request, fn: Callable[[Any, Any], Any], status: int = 200) -> JSONResponse:
    try:
        ctx = _ctx(request)
        with begin() as db:
            result = fn(db, ctx)
    except LookupError as exc:
        return JSONResponse({"error": "not_found", "detail": str(exc)}, status_code=404)
    except ValueError as exc:
        return JSONResponse({"error": "invalid", "detail": str(exc)}, status_code=400)
    except PermissionError as exc:
        return JSONResponse({"error": "forbidden", "detail": str(exc)}, status_code=403)
    return JSONResponse(result, status_code=status, headers={"Cache-Control": "no-store"})


