"""BOSS as an OpenID Connect provider for the apps it builds (F6). Stream S6.

Spec: docs/product/APP_TEMPLATES_AND_SECURITY_LOOP.md §6.2 (protocol) and §6.5 (admin API). The
protocol lives in engine/boss_engine/oidc_provider/; this module only turns requests into calls
and Replies into responses.

- Protocol endpoints live under the issuer, `/oidc/{org_slug}` (the slug is the org id). They are
  public by necessity: discovery and the JWKS publish nothing secret (`jwks`); the rest are
  `oidc_provider_endpoint` (IDENTITY_BUILD.md §7, AP-2): each authenticates by what the protocol
  says, never by a BOSS credential: `authorize` (and its `resume` and `consent` steps) by the
  console session plus `oidc_app:sign_in` (workforce pool), with PKCE S256 always; `token` and
  `revocation` by client authentication; `userinfo` by an app access token. An OIDC token is never
  accepted by BOSS's own verifiers, and a BOSS token is never accepted here (`typ` and key-family
  separation).
- ID tokens are RS256 by default, EdDSA opt-in per client (D10; IDENTITY.md D35).
- Admin routes (`/v1/oidc/*`) are ordinary permitted routes. Client secrets are generated by
  BOSS, shown once, and otherwise returned as presence only.
"""
