def _has_compose():
    return bool(shutil.which("docker")) and subprocess.run(
        ["docker", "compose", "version"], capture_output=True).returncode == 0


@pytest.mark.skipif(not _has_compose(), reason="docker compose is not available")
def test_compose_merges_the_overlay_into_the_real_compose_file(tmp_path):
    """The real base file plus the overlay: api/worker/runner get the options and keep their own
    environment; runner stays behind its profile; no other service changes."""
    install = _install(tmp_path, "BOSS_ENGINE_INNER_SANDBOX=seccomp+apparmor\n")
    shutil.copy2(ROOT / BASE, install / BASE)
    required = sorted(set(re.findall(r"\$\{([A-Z0-9_]+):\?", (ROOT / BASE).read_text())))
    with (install / ".env").open("a") as env_file:
        env_file.write("".join(f"{name}=x\n" for name in required))
    files = _resolve(install).stdout.splitlines()
    env = {k: v for k, v in os.environ.items() if not k.startswith(("BOSS_", "COMPOSE_"))}

    def config(*extra):
        return subprocess.run(["docker", "compose", *files, "--env-file", str(install / ".env"),
                               *extra, "config", "--format", "json"],
                              capture_output=True, text=True, timeout=60, env=env)

    done = config()
    assert done.returncode == 0, done.stderr
    services = json.loads(done.stdout)["services"]
    assert "runner" not in services                       # still behind its profile
    for name in ("api", "worker"):
        assert "apparmor=boss-engine" in services[name]["security_opt"]
        assert services[name]["environment"]["BOSS_ENGINE_INNER_SANDBOX"] == "seccomp+apparmor"
        assert "DATABASE_URL" in services[name]["environment"]
        assert "SYS_ADMIN" not in json.dumps(services[name].get("cap_add", []))
        assert not services[name].get("privileged")
    assert not [n for n, s in services.items() if n not in ("api", "worker") and "security_opt" in s]
    runner = json.loads(config("--profile", "runner").stdout)["services"]["runner"]
    assert "apparmor=boss-engine" in runner["security_opt"]


def _fake_docker(tmp_path):
    log = tmp_path / "docker.log"
    fake = tmp_path / "bin" / "docker"
    fake.parent.mkdir(parents=True, exist_ok=True)
    fake.write_text("#!/bin/sh\nprintf '%s\\n' \"$*\" >> " + shlex.quote(str(log)) + "\nexit 0\n")
    fake.chmod(0o755)
    return fake, log


@pytest.mark.parametrize("value,overlay", [("", False), ("seccomp", True)])
def test_boss_start_uses_the_resolver(tmp_path, value, overlay):
    install = _install(tmp_path, f"BOSS_ENGINE_INNER_SANDBOX={value}\n")
    fake, log = _fake_docker(tmp_path)
    env = {k: v for k, v in os.environ.items()
           if not k.startswith(("BOSS_", "DOCKER_", "COMPOSE_"))}
    env["PATH"] = f"{fake.parent}:{env['PATH']}"
    done = subprocess.run(["bash", str(ROOT / "scripts/install/boss.sh"), "--dir", str(install),
                           "start"], capture_output=True, text=True, timeout=60, env=env)
    assert done.returncode == 0, done.stdout + done.stderr
    up = [line for line in log.read_text().splitlines()
          if line.startswith("compose ") and " up " in line]
    assert up, log.read_text()
    assert ("engine-sandbox.compose.yml" in up[0]) is overlay


@pytest.mark.parametrize("value,overlay", [("", False), ("seccomp+apparmor", True)])
def test_the_self_fix_installer_uses_the_resolver(tmp_path, value, overlay, monkeypatch):
    install = _install(tmp_path, f"BOSS_ENGINE_INNER_SANDBOX={value}\n")
    fake, log = _fake_docker(tmp_path)
    spec = importlib.util.spec_from_file_location("self_fix_installer_under_test",
                                                  ROOT / "scripts/install/self_fix_installer.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    monkeypatch.setenv("BOSS_SELF_FIX_DOCKER", str(fake))
    host = module.Host(install)
    code, _ = host.compose("up", "-d", "--no-build")
    # A build from a worktree keeps ITS base file, and this install's overlay.
    host.compose("build", compose_file=tmp_path / "wt" / BASE)
    assert code == 0
    up, build = log.read_text().splitlines()
    assert ("engine-sandbox.compose.yml" in up) is overlay
    assert f"-f {tmp_path}/wt/{BASE}" in build
    assert ("engine-sandbox.compose.yml" in build) is overlay


def test_the_installer_block_uses_the_resolver(tmp_path):
    install = _install(tmp_path, "BOSS_ENGINE_INNER_SANDBOX=seccomp\n")
    source = (ROOT / "install.sh").read_text()
    block = source.split("# ---- compose files ---", 1)[1].split("# ---- end compose files ---", 1)[0]
    script = ("set -euo pipefail\ndie() { echo \"$*\" >&2; exit 1; }\nENV_FILE=.env\n"
              + block.split("\n", 1)[1] + '\nprintf "%s" "$COMPOSE_FILES"\n')
    done = subprocess.run(["bash", "-c", script], cwd=install, capture_output=True, text=True,
                          timeout=30)
    assert done.returncode == 0, done.stderr
    assert done.stdout.split() == ["-f", BASE, "-f", ".boss/engine-sandbox.compose.yml"]
    # Every compose call after the block uses it; none names the base file alone.
    after = source.split("# ---- end compose files ---", 1)[1]
    assert after.count("-f scripts/install/community-compose.yml") == \
        after.count("${COMPOSE_FILES:--f scripts/install/community-compose.yml}") >= 10


