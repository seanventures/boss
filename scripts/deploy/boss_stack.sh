#!/usr/bin/env bash
# BOSS deploying BOSS: the steps boss.deploy.yaml declares, run on the host by a governed
# stack deployment (docs/community/DEPLOY_A_STACK.md).
#
#   boss_stack.sh install  --dir DIR --commit SHA --state DIR/.boss/boss --origin https://HOST
#   boss_stack.sh update   (same flags)
#   boss_stack.sh https    --origin https://HOST [--web-port 3000]
#   boss_stack.sh teardown --dir DIR
#
# NOTHING HERE REPLACES THE INSTALLER. install/update run the repository's own install.sh with
# the flags README.md documents for an unattended install; this file only does what a stack
# deployment's layout needs around it:
#
#   * The deployment extracts each commit to DIR/releases/SHA and points DIR/current at it.
#     That is a shipped tree, exactly what remote.sh produces, so it is stamped with
#     .boss-shipped-commit and install.sh uses it as the source without fetching anything.
#   * install.sh keeps its credentials in INSTALL_DIR/.env. A new release directory has none,
#     and an installer that finds none generates new ones — which no longer open the Postgres
#     volume the previous release created. So .env (and the shell env file) live in STATE and
#     are copied into each release before the installer runs, and back out after it, even when
#     it fails part-way (it may have written fresh credentials the database already uses).
#   * An update backs up first with scripts/install/backup.sh, as remote.sh update does.
#   * install.sh runs ONE compose project per host (COMPOSE_PROJECT_NAME, default
#     boss-community) on fixed ports. A host that already runs a BOSS installed some other way
#     (the README install in ~/boss) is refused: deploying here would recreate that install's
#     containers from this tree with fresh credentials its database volume rejects.
#   * install.sh writes the `boss` launcher with the physically resolved install dir, which is
#     DIR/releases/SHA — pruned a few deploys later. The launcher is pointed at DIR (the
#     `current` link) so `boss status|upgrade|backup` keep working across releases.
#
# Credentials are never printed: only file names are mentioned.
set -euo pipefail
umask 077

die() { echo "boss_stack: $*" >&2; exit 2; }

action="${1:-}"; shift || true
DIR="" COMMIT="" STATE="" ORIGIN="" WEB_PORT=3000
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dir) DIR="${2:?--dir needs a path}"; shift 2 ;;
    --commit) COMMIT="${2:?--commit needs a sha}"; shift 2 ;;
    --state) STATE="${2:?--state needs a path}"; shift 2 ;;
    --origin) ORIGIN="${2:?--origin needs an https origin}"; shift 2 ;;
    --web-port) WEB_PORT="${2:?--web-port needs a number}"; shift 2 ;;
    *) die "unknown option: $1" ;;
  esac
done

PRIVATE_FILES=(.env boss-community.env.sh)
PROJECT="${COMPOSE_PROJECT_NAME:-boss-community}"
BOSS_COMMAND_MARKER="# BOSS Community command (generated by install.sh)"

# Docker as this user, or through passwordless sudo, as install.sh would reach it. Empty when
# neither works (no Docker yet: nothing can be running).
DOCKER=()
find_docker() {
  command -v docker >/dev/null 2>&1 || return 0
  if docker info >/dev/null 2>&1; then
    DOCKER=(docker)
  elif sudo -n docker info >/dev/null 2>&1; then
    DOCKER=(sudo -n docker)
  fi
}

# The stack's own directory: DIR is <stack>/current or <stack>/releases/<sha>.
stack_root() {
  local root
  root="$(dirname "$DIR")"
  [[ "$(basename "$root")" == releases ]] && root="$(dirname "$root")"
  printf '%s\n' "$root"
}

# Refuse to take over a BOSS this stack did not install (see the header).
refuse_foreign_install() {
  find_docker
  [[ ${#DOCKER[@]} -gt 0 ]] || return 0
  local root physical files file
  root="$(stack_root)"
  physical="$(cd "$root" && pwd -P)"
  files="$("${DOCKER[@]}" compose ls -a 2>/dev/null | awk -v p="$PROJECT" '$1 == p {print $NF}' ||
           true)"
  if [[ -n "$files" ]]; then
    IFS=',' read -r -a files <<< "$files"
    for file in "${files[@]}"; do
      case "$file" in
        "$root"/*|"$physical"/*) ;;
        *)
          echo "boss_stack: this host already runs a BOSS install (compose project $PROJECT," \
               "from $(dirname "$(dirname "$(dirname "$file")")"))." >&2
          echo "boss_stack: deploying here would replace its containers with ones its" \
               "database does not accept. Deploy to another host, or remove that install" \
               "first (boss uninstall in its directory), then deploy again." >&2
          exit 3 ;;
      esac
    done
    return 0
  fi
  if [[ ! -f "$STATE/.env" ]] &&
     "${DOCKER[@]}" volume inspect "${PROJECT}_boss_community_pg" >/dev/null 2>&1; then
    echo "boss_stack: this host keeps the database volume of an earlier BOSS install" \
         "(${PROJECT}_boss_community_pg), and this deployment has no credentials for it." >&2
    echo "boss_stack: restore that install's .env into $STATE, or remove the volume if its" \
         "data is not needed (docker volume rm ${PROJECT}_boss_community_pg), then deploy again." >&2
    exit 3
  fi
}

# Point install.sh's `boss` launcher at DIR (the stable link) instead of the release it
# resolved DIR to. Only a launcher install.sh wrote for exactly this release is touched.
stable_launcher() {
  local physical candidate tmp
  physical="$(cd "$DIR" && pwd -P)"
  [[ "$physical" != "$DIR" ]] || return 0
  for candidate in "${BOSS_BIN_DIR:+$BOSS_BIN_DIR/boss}" "$HOME/.local/bin/boss" /usr/local/bin/boss; do
    [[ -n "$candidate" && -f "$candidate" && ! -L "$candidate" ]] || continue
    [[ "$(sed -n 2p "$candidate" 2>/dev/null)" == "$BOSS_COMMAND_MARKER" ]] || continue
    [[ "$(grep -m 1 '^BOSS_INSTALL_DIR_DEFAULT=' "$candidate" | cut -d= -f2-)" == \
       "$(printf '%q' "$physical")" ]] || continue
    tmp="$candidate.boss-stack.$$"
    LINE="BOSS_INSTALL_DIR_DEFAULT=$(printf '%q' "$DIR")" awk \
      '/^BOSS_INSTALL_DIR_DEFAULT=/ && !done { print ENVIRON["LINE"]; done = 1; next } { print }' \
      "$candidate" > "$tmp"
    chmod 755 "$tmp"
    mv -f "$tmp" "$candidate"
    echo "boss_stack: $candidate now follows $DIR"
  done
}

carry_in() {
  mkdir -p "$STATE"
  chmod 700 "$STATE"
  local f
  for f in "${PRIVATE_FILES[@]}"; do
    if [[ -f "$STATE/$f" ]]; then
      cp -p "$STATE/$f" "$DIR/$f"
      chmod 600 "$DIR/$f"
    fi
  done
}

carry_out() {
  local f
  for f in "${PRIVATE_FILES[@]}"; do
    if [[ -f "$DIR/$f" ]]; then
      install -m 600 "$DIR/$f" "$STATE/$f"
    fi
  done
}

run_installer() {
  [[ -n "$DIR" && -n "$COMMIT" && -n "$STATE" && -n "$ORIGIN" ]] ||
    die "$action needs --dir, --commit, --state and --origin"
  [[ "$COMMIT" =~ ^[0-9a-fA-F]{7,40}$ ]] || die "--commit must be a commit sha"
  [[ -f "$DIR/install.sh" && -f "$DIR/scripts/install/community-compose.yml" ]] ||
    die "$DIR is not a BOSS source tree"
  refuse_foreign_install
  printf '%s\n' "$COMMIT" > "$DIR/.boss-shipped-commit"
  carry_in
  if [[ "$action" == update && -f "$DIR/.env" ]]; then
    echo "boss_stack: backing up the running install before the update"
    bash "$DIR/scripts/install/backup.sh" --dir "$DIR"
  fi
  local rc=0
  # README.md "Deploy", unattended: --yes answers no to every optional question and
  # --skip-model-key leaves models to be connected from the console.
  bash "$DIR/install.sh" --dir "$DIR" --yes --skip-model-key --console-origin "$ORIGIN" || rc=$?
  carry_out
  stable_launcher
  return "$rc"
}

# Caddy from the distribution when it has it (Debian 12+, Ubuntu 24.04), else from Caddy's own
# apt repository, as https://caddyserver.com/docs/install documents (Ubuntu 22.04 has no
# package). The package lists are refreshed first: a fresh cloud image ships with none.
CADDY_REPO=https://dl.cloudsmith.io/public/caddy/stable
CADDY_KEYRING=/usr/share/keyrings/caddy-stable-archive-keyring.gpg
CADDY_LIST=/etc/apt/sources.list.d/caddy-stable.list
install_caddy() {
  command -v caddy >/dev/null 2>&1 && return 0
  command -v apt-get >/dev/null 2>&1 ||
    die "Caddy is not installed and this host has no apt-get. Install Caddy (https://caddyserver.com/docs/install), then deploy again."
  local apt=(sudo -n env DEBIAN_FRONTEND=noninteractive apt-get -y -qq) policy
  echo "boss_stack: installing Caddy"
  "${apt[@]}" update
  policy="$(apt-cache policy caddy 2>/dev/null || true)"
  if [[ ! "$policy" =~ Candidate:\ [0-9] ]]; then
    echo "boss_stack: this release has no caddy package; adding Caddy's apt repository"
    "${apt[@]}" install ca-certificates curl gnupg
    curl -1sLf "$CADDY_REPO/gpg.key" | sudo -n gpg --batch --yes --dearmor -o "$CADDY_KEYRING"
    curl -1sLf "$CADDY_REPO/debian.deb.txt" | sudo -n tee "$CADDY_LIST" >/dev/null
    sudo -n chmod o+r "$CADDY_KEYRING" "$CADDY_LIST"
    "${apt[@]}" update
  fi
  "${apt[@]}" install caddy ||
    die "apt-get could not install Caddy. Install it (https://caddyserver.com/docs/install), then deploy again."
}

# README.md step 3, "Put HTTPS in front", as a command. It never replaces a Caddyfile that
# serves anything else: it writes only over a missing file, the package's default, or the
# block it wrote itself, and otherwise stops and prints the block to add by hand.
https_proxy() {
  [[ -n "$ORIGIN" ]] || die "https needs --origin"
  case "$ORIGIN" in
    https://*) ;;
    *) echo "boss_stack: $ORIGIN is not https; no proxy configured"; return 0 ;;
  esac
  local host="${ORIGIN#https://}"
  host="${host%%/*}"
  [[ "$host" =~ ^[A-Za-z0-9.-]+$ ]] || die "cannot proxy $host: use a hostname or an IPv4 address"
  local tls=""
  [[ "$host" =~ ^[0-9]+(\.[0-9]+){3}$ ]] && tls=$'\n    tls internal'
  local marker="# Written by BOSS (scripts/deploy/boss_stack.sh https) for $host"
  local block
  block="$marker
$host {$tls
    reverse_proxy 127.0.0.1:$WEB_PORT {
        header_up Host $host
        header_up X-Forwarded-Host $host
        header_up X-Forwarded-Proto https
    }
}"
  local caddyfile=/etc/caddy/Caddyfile
  install_caddy
  # The package default serves a static page and proxies nothing; any live proxy or app
  # directive means someone else's site is in this file.
  if [[ -f "$caddyfile" ]] && ! grep -qF "$marker" "$caddyfile" &&
     grep -qE '^[^#]*(reverse_proxy|php_fastcgi|redir)' "$caddyfile"; then
    echo "boss_stack: $caddyfile already serves other sites; it was left unchanged." >&2
    echo "boss_stack: add this block to it, then run: sudo systemctl reload caddy" >&2
    printf '%s\n' "$block" >&2
    return 1
  fi
  local tmp
  tmp="$(mktemp)"
  printf '%s\n' "$block" > "$tmp"
  sudo -n caddy validate --adapter caddyfile --config "$tmp" >/dev/null
  sudo -n install -m 644 "$tmp" "$caddyfile"
  rm -f "$tmp"
  sudo -n systemctl reload caddy || sudo -n systemctl restart caddy
  echo "boss_stack: Caddy serves $ORIGIN -> 127.0.0.1:$WEB_PORT"
}

case "$action" in
  install|update) run_installer ;;
  https) https_proxy ;;
  teardown)
    [[ -n "$DIR" ]] || die "teardown needs --dir"
    # The safe uninstall: stops the stack, keeps data, credentials and backups.
    bash "$DIR/scripts/install/uninstall.sh" --dir "$DIR" --yes ;;
  *) die "usage: boss_stack.sh install|update|https|teardown [options]" ;;
esac
