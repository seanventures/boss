#!/usr/bin/env python3
"""Generate docs/api/ROUTE_INDEX.md from FastAPI route decorators.

Parses:
  - apps/api/app/main.py          (@app.get/post/...)
  - apps/api/app/routers/governance.py  (@router.get/post/...)

Groups routes by the first two path segments (e.g. /v1/budget).
Does not import the app (no DB/settings required).

Usage:
  python scripts/generate_api_route_index.py
  PYTHONPATH=.:engine python scripts/generate_api_route_index.py  # same
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAIN = ROOT / "apps" / "api" / "app" / "main.py"
GOVERNANCE = ROOT / "apps" / "api" / "app" / "routers" / "governance.py"
OUT = ROOT / "docs" / "api" / "ROUTE_INDEX.md"

# Match @app.get("/path"...) and multiline @app.get(\n  "/path"
DECORATOR_RE = re.compile(
    r"@(?P<target>app|router)\."
    r"(?P<method>get|post|put|patch|delete|head|options|api_route)"
    r"\(\s*(?:methods\s*=\s*\[(?P<methods>[^\]]+)\]\s*,\s*)?"
    r"(?P<path>[\"'][^\"']+[\"'])",
    re.MULTILINE | re.DOTALL,
)

# api_route with path first, methods later
API_ROUTE_PATH_FIRST = re.compile(
    r"@(?P<target>app|router)\.api_route\(\s*(?P<path>[\"'][^\"']+[\"'])"
    r"(?P<rest>[^)]*)\)",
    re.MULTILINE | re.DOTALL,
)


def _clean_path(raw: str) -> str:
    return raw.strip().strip("\"'")


def _methods_from_api_route(rest: str, default: str = "GET") -> list[str]:
    m = re.search(r"methods\s*=\s*\[([^\]]+)\]", rest or "")
    if not m:
        return [default.upper()]
    found = re.findall(r"[\"'](\w+)[\"']", m.group(1))
    return [x.upper() for x in found] if found else [default.upper()]


def collect_routes() -> list[tuple[str, str, str]]:
    """Return list of (METHOD, path, source_file_relative)."""
    sources = [
        (MAIN, "apps/api/app/main.py", "app"),
        (GOVERNANCE, "apps/api/app/routers/governance.py", "router"),
    ]
    seen: set[tuple[str, str]] = set()
    routes: list[tuple[str, str, str]] = []

    for path, rel, expected_target in sources:
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")

        for m in DECORATOR_RE.finditer(text):
            target = m.group("target")
            if target != expected_target:
                continue
            method_name = m.group("method")
            route_path = _clean_path(m.group("path"))
            if method_name == "api_route":
                methods = _methods_from_api_route(m.group("methods") or "")
                # methods group only filled when methods= precedes path; fallback
                if not methods or methods == [""]:
                    # re-scan with path-first pattern for this decorator region
                    continue
            else:
                methods = [method_name.upper()]
            for method in methods:
                key = (method, route_path)
                if key in seen:
                    continue
                seen.add(key)
                routes.append((method, route_path, rel))

        # Catch api_route where path is first argument
        for m in API_ROUTE_PATH_FIRST.finditer(text):
            target = m.group("target")
            if target != expected_target:
                continue
            route_path = _clean_path(m.group("path"))
            methods = _methods_from_api_route(m.group("rest"))
            for method in methods:
                if method in {"HEAD", "OPTIONS"}:
                    continue
                key = (method, route_path)
                if key in seen:
                    continue
                seen.add(key)
                routes.append((method, route_path, rel))

    routes.sort(key=lambda r: (r[1], r[0]))
    return routes


def group_key(path: str) -> str:
    parts = [p for p in path.split("/") if p]
    if len(parts) >= 2:
        return f"/{parts[0]}/{parts[1]}"
    if len(parts) == 1:
        return f"/{parts[0]}"
    return "/"


def render(routes: list[tuple[str, str, str]]) -> str:
    groups: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for method, path, src in routes:
        groups[group_key(path)].append((method, path, src))

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# BOSS API route index",
        "",
        f"_Generated by `scripts/generate_api_route_index.py` on {now}._",
        "",
        "Do not edit by hand. Regenerate with:",
        "",
        "```bash",
        "python scripts/generate_api_route_index.py",
        "```",
        "",
        f"**Total routes:** {len(routes)}",
        f"**Groups:** {len(groups)}",
        "",
        "Sources:",
        "",
        "- `apps/api/app/main.py`",
        "- `apps/api/app/routers/governance.py`",
        "",
        "Grouping key = first two path segments (e.g. `/v1/budget`).",
        "",
        "---",
        "",
    ]

    for gkey in sorted(groups.keys()):
        items = groups[gkey]
        lines.append(f"## `{gkey}` ({len(items)})")
        lines.append("")
        lines.append("| Method | Path | Source |")
        lines.append("|--------|------|--------|")
        for method, path, src in items:
            short = "main.py" if src.endswith("main.py") else "governance.py"
            lines.append(f"| `{method}` | `{path}` | {short} |")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("See also: [API docs index](README.md) · [OpenAPI](../../api/openapi.yaml) · "
                 "`GET /v1/meta/api-catalog`")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    routes = collect_routes()
    if not routes:
        print("error: no routes found", file=sys.stderr)
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(routes), encoding="utf-8")
    groups = {group_key(p) for _, p, _ in routes}
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(routes)} routes in {len(groups)} groups")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
