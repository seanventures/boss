#!/usr/bin/env python3
"""Regenerate the reviewed Community bootstrap schema from the private source.

This script stays in the source repository. The export maps only the generated
SQL to db/schema.sql after checking its SHA-256. A source schema change requires
an explicit review of the table boundary before this pin is updated.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "db/schema.sql"
OUTPUT = ROOT / "db/schema.community.sql"
REVIEWED_SOURCE_SHA256 = "0d65b2b70e7e75a890265401a725953acf3476d3ca08c3cf1cc515dab08d7136"

# Optional Easy Connect retains its local org/auth/health/worker records. Only
# hosted seat/billing/marketplace and Enterprise cluster/support records are
# omitted. Local entitlements and self-hosted identity/SSO/SCIM remain.
PAID_TABLES = frozenset(
    {
        "enterprise_clusters",
        "enterprise_cluster_validation_runs",
        "enterprise_support_cases",
        "account_connect_team_invites",
        "account_connect_billing_portal_sessions",
        "hosted_marketplace_sync_runs",
        "hosted_marketplace_pack_listings",
    }
)
TABLE_START = re.compile(r"(?m)^CREATE TABLE IF NOT EXISTS ([a-z][a-z0-9_]*) \(")
PAID_MARKERS = (
    "hosted_marketplace",
    "enterprise_cluster",
    "enterprise_support_cases",
    "account_connect_team_invites",
    "account_connect_billing_portal_sessions",
)


def render(source: bytes) -> str:
    if hashlib.sha256(source).hexdigest() != REVIEWED_SOURCE_SHA256:
        raise ValueError("source schema changed; review the Community table boundary")
    text = source.decode("utf-8")
    starts = list(TABLE_START.finditer(text))
    if not starts:
        raise ValueError("source schema contains no tables")
    seen: set[str] = set()
    result = [text[: starts[0].start()]]
    for index, match in enumerate(starts):
        name = match.group(1)
        if name in seen:
            raise ValueError(f"duplicate table declaration: {name}")
        seen.add(name)
        end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
        segment = text[match.start() : end]
        if name in PAID_TABLES:
            # Each omitted segment contains only its own table/index DDL and
            # comments. This catches a future shared ALTER hidden in the span.
            altered = set(re.findall(r"(?m)^ALTER TABLE ([a-z][a-z0-9_]*)", segment))
            indexed = set(re.findall(r"(?m)^  ON ([a-z][a-z0-9_]*)\(", segment))
            if altered - {name} or indexed - {name}:
                raise ValueError(f"paid table span gained shared DDL: {name}")
            continue
        result.append(segment)
    if not PAID_TABLES <= seen:
        raise ValueError(f"paid table declarations missing: {sorted(PAID_TABLES - seen)}")
    rendered = "".join(result)
    if any(marker in rendered for marker in PAID_MARKERS):
        raise ValueError("paid schema reference survived Community split")
    included = set(TABLE_START.findall(rendered))
    for referenced in re.findall(r"\bREFERENCES ([a-z][a-z0-9_]*)\(", rendered):
        if referenced not in included:
            raise ValueError(f"Community FK references missing table: {referenced}")
    return "-- Community bootstrap schema. Generated by scripts/build_community_schema.py.\n" + rendered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in SQL has drifted")
    args = parser.parse_args()
    generated = render(SOURCE.read_bytes())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Community schema is stale; regenerate after source review")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Community schema: {len(TABLE_START.findall(generated))} tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
