"""HelpDesk crun_5344bcfa died with PermissionError on Path(workdir/node_modules/.bin).is_dir():
the sandbox uid made node_modules and BOSS's uid could not stat inside it. A refused stat is
"not here", never a crash."""
import inspect

from boss_engine.services import sandbox


def test_the_local_bin_probe_is_guarded():
    src = inspect.getsource(sandbox)
    at = src.index('local_bin = str(Path(workdir) / "node_modules" / ".bin")')
    probe = src[at:at + 900]
    assert "except OSError" in probe and "has_bin = False" in probe
    assert "if local_bin and Path(local_bin).is_dir():" not in src


def test_the_diff_skips_build_output_and_reports_an_unreadable_file(tmp_path, monkeypatch):
    """crun_bcbec2f6 died reading test-results/.last-run.json while computing its diff."""
    from boss_engine.services import repo_files

    box = sandbox.EphemeralSandbox.__new__(sandbox.EphemeralSandbox)
    box.path = tmp_path
    box._repo_files = None
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "app.ts").write_text("ok")
    (tmp_path / "src" / "locked.ts").write_text("x")

    class S:  # diff_summary stand-in
        paths = ["test-results/.last-run.json", "src/app.ts", "src/locked.ts"]
    monkeypatch.setattr(sandbox.EphemeralSandbox, "diff_summary", lambda self: S())
    real = repo_files.RepoFiles.read_text

    def read(self, path, **kw):
        if path == "src/locked.ts":
            try:
                raise PermissionError(13, "denied")
            except PermissionError as exc:
                raise repo_files.RepoFileRefused("refused") from exc
        return real(self, path, **kw)
    monkeypatch.setattr(repo_files.RepoFiles, "read_text", read)
    changes = box.diff()
    assert [c.path for c in changes] == ["src/app.ts"]
    assert box.unreadable_paths == ["src/locked.ts"]


def test_every_sandbox_command_tidies_the_workspace_after_it_runs():
    """The test run's test-results/ (sandbox uid only) crashed BOSS's regression check next."""
    assert getattr(sandbox.EphemeralSandbox.run, "__boss_tidies_after_command__", False)


def test_normalize_makes_everything_the_run_made_readable_to_boss(tmp_path, monkeypatch):
    """crun_8e9b3b0e: BOSS could not read the template junit report, dist/ or node_modules/."""
    from boss_engine.services import workspace_perms as wp

    calls = []
    monkeypatch.setattr(wp, "_identity", lambda root: object())
    monkeypatch.setattr(wp, "_as_run_uid", lambda ident, script, *a: calls.append(script) or True)
    wp.normalize(tmp_path)
    assert wp._READABLE in calls
    assert "a+rw" in wp._READABLE and "a+rwx" in wp._READABLE and "-user" in wp._READABLE


