def test_normalize_makes_everything_the_run_made_readable_to_boss(tmp_path, monkeypatch):
    """crun_8e9b3b0e: BOSS could not read the template junit report, dist/ or node_modules/."""
    from boss_engine.services import workspace_perms as wp

    calls = []
    monkeypatch.setattr(wp, "_identity", lambda root: object())
    monkeypatch.setattr(wp, "_as_run_uid", lambda ident, script, *a: calls.append(script) or True)
    wp.normalize(tmp_path)
    assert wp._READABLE in calls
    assert "a+rw" in wp._READABLE and "a+rwx" in wp._READABLE and "-user" in wp._READABLE


