def test_the_diff_is_against_the_base_commit_even_after_the_agent_commits(tmp_path):
    """crun_a3a733ed: the agent committed, HEAD moved, the diff was empty (impl_files 0)."""
    import subprocess

    def git(*a):
        return subprocess.run(["git", *a], cwd=tmp_path, capture_output=True, text=True, check=True).stdout

    git("init", "-q"); git("config", "user.email", "t@example.com"); git("config", "user.name", "t")
    (tmp_path / "README.md").write_text("base")
    git("add", "-A"); git("commit", "-qm", "base")
    base = git("rev-parse", "HEAD").strip()
    (tmp_path / "app").mkdir(); (tmp_path / "app" / "server.mjs").write_text("x")
    git("add", "-A"); git("commit", "-qm", "the agent committed its work")
    box = sandbox.EphemeralSandbox.__new__(sandbox.EphemeralSandbox)
    box.path = tmp_path
    box.diff_base_sha = base
    box._git = lambda args, **kw: git(*args)
    assert box.diff_summary().paths == ["app/server.mjs"]


def test_an_agents_own_commit_is_put_back_into_the_index(tmp_path):
    """crun_86902c82: the agent committed; the reviewer saw 'no changes relative to HEAD'."""
    import subprocess

    def git(*a):
        return subprocess.run(["git", *a], cwd=tmp_path, capture_output=True, text=True, check=True).stdout

    git("init", "-q"); git("config", "user.email", "t@example.com"); git("config", "user.name", "t")
    (tmp_path / "README.md").write_text("base"); git("add", "-A"); git("commit", "-qm", "base")
    base = git("rev-parse", "HEAD").strip()
    (tmp_path / "app.mjs").write_text("x"); git("add", "-A"); git("commit", "-qm", "agent")
    box = sandbox.EphemeralSandbox.__new__(sandbox.EphemeralSandbox)
    box.path = tmp_path
    box.diff_base_sha = base
    box._git = lambda args, **kw: git(*args)
    assert box.undo_agent_commits() is True
    assert git("rev-parse", "HEAD").strip() == base
    assert "app.mjs" in git("diff", "--cached", "--name-only")
