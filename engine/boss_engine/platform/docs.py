"""Generated docs: docs/community/support-matrix.md comes from the registry, never by hand.

    python -m boss_engine.platform matrix --write

`test_platform_docs.py` fails when the committed file differs from what this renders, so a
plugin added, removed or re-levelled without regenerating the matrix does not merge.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

from .registry import Registry, discover, plugins_root, support_matrix

HEADER = ("<!-- GENERATED by engine/boss_engine/platform/docs.py from the plugin registry. "
          "Do not edit: run `python -m boss_engine.platform matrix --write`. -->\n")

LEVELS = {
    "certified": "every lifecycle stage tested in CI against pinned versions",
    "experimental": "a documented subset works; some stages are unverified",
    "community": "third-party; no BOSS-maintainer certification promise",
}


def support_matrix_path() -> Path:
    return plugins_root().parent / "docs" / "community" / "support-matrix.md"


def render_support_matrix(root: Optional[Path] = None) -> str:
    root = (root or plugins_root()).resolve()
    # Only what ships in the repository: an operator's extra BOSS_PLUGIN_PATHS never reach the doc.
    plugins = [p for p in discover(root) if root in p.directory.resolve().parents]
    rows = support_matrix(Registry(plugins))
    out = [HEADER, "# Infrastructure plugin support matrix", "",
           "What each plugin in this repository provides, and what BOSS promises about it.", ""]
    for level, words in LEVELS.items():
        out.append(f"- **{level}**: {words}")
    out += ["", "| Plugin | Version | Source | Support | Capabilities | Engines | Hooks |",
            "|---|---|---|---|---|---|---|"]
    for r in rows:
        engines = ", ".join(r["engines"]) or "-"
        if r["engineVersions"]:
            engines += f" ({', '.join(r['engineVersions'])})"
        out.append(f"| `{r['id']}` | {r['version']} | {r['source']} | {r['supportLevel']} | "
                   f"{', '.join(r['capabilities'])} | {engines} | {', '.join(r['hooks'])} |")
    if not rows:
        out.append("| (none) | | | | | | |")
    out += ["", "`validate` is implemented by every plugin and not listed.", ""]
    return "\n".join(out)
