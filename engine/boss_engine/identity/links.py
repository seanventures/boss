"""EVERY LINK THE ENGINE MINTS, IN ONE TABLE: kind -> console page -> the fragment key it reads.

boss-1 (2026-10-07): `boss identity recover-owner` printed `/auth/recover#token=…`, a page the
console never had. The browser was sent to /login with the token still in the URL, and the page
that DOES consume that token (/reset) reads `#t=`. Each link was an f-string in its own module,
spelled from memory.

Now a link is `links.url(kind, origin, token)` and nothing else. The console reads the same table
(apps/web/lib/identity/auth-links.gen.ts, generated from this file: `python -m
boss_engine.identity.links --write`), and two tests walk it:
  * apps/api/tests/test_every_minted_link_lands_on_a_real_page.py — the generated file is current,
    every path is a page under apps/web/app that the middleware lets through without a session,
    and no engine/API module spells a link by hand;
  * apps/web/tests/every-minted-link-lands-on-a-real-page.test.ts — each page reads its token
    with `linkToken(kind)` (the table's fragment key), and is public.

The token always rides in the FRAGMENT: it never reaches a request line, an access log or a
proxy (A88). An email code is typed, not followed, so it has no link.
"""
from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote


@dataclass(frozen=True)
class AuthLink:
    kind: str
    path: str        # the console page (a public route under apps/web/app)
    fragment: str    # the fragment key that page reads the token from
    purpose: str


AUTH_LINKS: dict[str, AuthLink] = {link.kind: link for link in (
    AuthLink("setup", "/claim", "t", "Claim this BOSS: the first Owner (install output, an hour)"),
    AuthLink("invite", "/invite", "t", "Accept an invitation (7 days)"),
    AuthLink("reset", "/reset", "t", "Set a new password (emailed or issued by an admin)"),
    # The host's break-glass mints a password_reset challenge: /reset consumes it, then the
    # first-factor grant takes the Owner straight into enrolment.
    AuthLink("recover_owner", "/reset", "t", "`boss identity recover-owner` on the host (15 minutes)"),
    AuthLink("magic_link", "/signin/link", "t", "Emailed one-click sign-in (10 minutes)"),
    AuthLink("signup_verify", "/signup/verify", "t", "Finish a self sign-up (10 minutes)"),
)}

#: Links already printed by an older build. Each page forwards to its kind's page with the token
#: moved to the right fragment key; never a page of its own.
LEGACY_ALIASES: dict[str, tuple[str, str]] = {
    "/auth/recover": ("recover_owner", "token"),
}


def url(kind: str, origin: str, token: str) -> str:
    """The link for `kind` on `origin` (no trailing slash needed), its token in the fragment."""
    link = AUTH_LINKS[kind]
    return f"{(origin or '').rstrip('/')}{link.path}#{link.fragment}={quote(token, safe='')}"


# ---- the console's copy ---------------------------------------------------------------------------

TS_PATH = Path(__file__).resolve().parents[3] / "apps" / "web" / "lib" / "identity" / "auth-links.gen.ts"


def render_ts() -> str:
    rows = "\n".join(f"  {k}: {{ path: {l.path!r}, fragment: {l.fragment!r} }},".replace("'", '"')
                     for k, l in AUTH_LINKS.items())
    aliases = "\n".join(f"  {p!r}: {{ kind: {k!r}, fragment: {f!r} }},".replace("'", '"')
                        for p, (k, f) in LEGACY_ALIASES.items())
    return (
        "// GENERATED by `python -m boss_engine.identity.links --write` from\n"
        "// engine/boss_engine/identity/links.py. Do not edit: every link the engine mints, the page it\n"
        "// lands on and the fragment key that page reads (a test fails when this copy is stale).\n\n"
        f"export const AUTH_LINKS = {{\n{rows}\n}} as const;\n\n"
        "export type AuthLinkKind = keyof typeof AUTH_LINKS;\n\n"
        "/** Links an older build printed: forwarded to their kind's page, never a page of their own. */\n"
        f"export const LEGACY_LINK_ALIASES: Record<string, {{ kind: AuthLinkKind; fragment: string }}> = {{\n{aliases}\n}};\n"
    )


def main(argv: list[str]) -> int:
    if "--write" in argv:
        TS_PATH.write_text(render_ts(), encoding="utf-8")
        print(f"wrote {TS_PATH}")
        return 0
    print(render_ts(), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
