"""Generate every derived form of the permission catalogue from packages/identity/catalogue.yaml.

    PYTHONPATH=engine python -m boss_engine.identity.codegen           write the outputs
    PYTHONPATH=engine python -m boss_engine.identity.codegen --check   exit 1 if any is stale

Outputs (each is committed; engine/tests/test_identity_catalogue_is_generated.py fails when one is
stale, so a catalogue edit cannot land without its consequences being reviewable in the diff):

    engine/boss_engine/identity/permissions_gen.py
    apps/web/lib/identity/permissions.gen.ts
    db/identity_seed.sql
    docs/product/IDENTITY_CATALOGUE.md

Output is deterministic: same YAML, same bytes. Nothing here runs in production.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from .catalogue import HUMAN_ROLES, SYSTEM_ROLES, Catalogue, load, repo_root

HEADER = "GENERATED by boss_engine.identity.codegen from packages/identity/catalogue.yaml. Do not edit."

OUTPUTS = {
    "python": Path("engine/boss_engine/identity/permissions_gen.py"),
    "typescript": Path("apps/web/lib/identity/permissions.gen.ts"),
    "sql": Path("db/identity_seed.sql"),
    "docs": Path("docs/product/IDENTITY_CATALOGUE.md"),
}


def fingerprint(c: Catalogue) -> str:
    """A hash of the catalogue's CONTENT (not its comments): changes exactly when meaning does."""
    body = {
        "permissions": [p.__dict__ for p in c.permissions],
        "roles": [r.__dict__ for r in c.roles],
        "presets": [{**s.__dict__, "external_ceiling": dict(s.external_ceiling)} for s in c.presets],
        "system_principals": [s.__dict__ for s in c.system_principals],
    }
    return hashlib.sha256(json.dumps(body, sort_keys=True, default=list).encode()).hexdigest()[:16]


def _enum_name(key: str) -> str:
    return key.replace(":", "_").upper()


def builtin_role_id(role_key: str) -> str:
    return f"arl_{role_key}"


# ---- Python ------------------------------------------------------------------------------------

def render_python(c: Catalogue) -> str:
    out = [f'"""{HEADER}"""', "# ruff: noqa: E501", "from __future__ import annotations", "",
           "from enum import StrEnum", "",
           "from .catalogue import AccessRoleMeta, PassportPreset, PermissionMeta, SystemPrincipalMeta",
           "", f"CATALOGUE_VERSION = {c.version}", f'CATALOGUE_FINGERPRINT = "{fingerprint(c)}"', "", "",
           "class Permission(StrEnum):",
           '    """Every catalogue permission. A str: `Permission.WORKFLOW_PUBLISH == "workflow:publish"`."""', ""]
    for p in c.permissions:
        out.append(f'    {_enum_name(p.key)} = "{p.key}"')
    out += ["", "", "#: Alias for declarations: `@permit(P.WORKFLOW_PUBLISH, ...)`.", "P = Permission", "",
            "PERMISSION_META: dict[str, PermissionMeta] = {"]
    for p in c.permissions:
        out.append(
            f'    "{p.key}": PermissionMeta(key="{p.key}", title={json.dumps(p.title)}, '
            f"description={json.dumps(p.description)}, category={json.dumps(p.category)}, "
            f"roles={tuple(p.roles)!r}, scope={p.scope!r}, step_up={p.step_up}, "
            f"delegable={p.delegable}, critical={p.critical}, system_only={p.system_only}, "
            f"readonly_post={p.readonly_post}),"
        )
    out += ["}", "", "ACCESS_ROLES: dict[str, AccessRoleMeta] = {"]
    for r in c.roles:
        out.append(
            f'    "{r.key}": AccessRoleMeta(key="{r.key}", name={json.dumps(r.name)}, '
            f"description={json.dumps(r.description)}, bindable_scopes={tuple(r.bindable_scopes)!r}, "
            f"mfa_required={r.mfa_required}, system={r.system}),"
        )
    out += ["}", "", "#: Built-in role -> its permissions. Derived ONLY from each entry's `roles`.",
            "ROLE_PERMISSIONS: dict[str, frozenset[str]] = {"]
    for r in c.roles:
        keys = c.role_permissions(r.key)
        out.append(f'    "{r.key}": frozenset({{  # {len(keys)}')
        for k in keys:
            out.append(f'        "{k}",')
        out.append("    }),")
    out += ["}", "", "PASSPORT_PRESETS: dict[str, PassportPreset] = {"]
    for s in c.presets:
        out.append(
            f'    "{s.key}": PassportPreset(key="{s.key}", name={json.dumps(s.name)}, '
            f"agents={tuple(s.agents)!r}, permissions={tuple(s.permissions)!r}, "
            f"external_ceiling={json.dumps(dict(s.external_ceiling), sort_keys=True)}),"
        )
    out += ["}", "", "SYSTEM_PRINCIPALS: dict[str, SystemPrincipalMeta] = {"]
    for s in c.system_principals:
        out.append(
            f'    "{s.id}": SystemPrincipalMeta(id="{s.id}", access_role="{s.access_role}", '
            f"replaces={json.dumps(s.replaces)}),"
        )
    out += ["}", ""]
    return "\n".join(out)


# ---- TypeScript ----------------------------------------------------------------------------------

def render_typescript(c: Catalogue) -> str:
    def ts(v: object) -> str:
        return json.dumps(v)

    out = [f"// {HEADER}", "//", "// The Permission type is a closed literal union: there is no `${string}` escape hatch, so a",
           "// misspelt permission anywhere in apps/web is a type error.", "",
           f"export const CATALOGUE_VERSION = {c.version} as const;",
           f'export const CATALOGUE_FINGERPRINT = "{fingerprint(c)}";', "",
           "export const PERMISSIONS = ["]
    for p in c.permissions:
        out.append(f'  "{p.key}",')
    out += ["] as const;", "", "export type Permission = (typeof PERMISSIONS)[number];", "",
            "export const ACCESS_ROLE_KEYS = [" + ", ".join(ts(r) for r in HUMAN_ROLES + SYSTEM_ROLES) + "] as const;",
            "export type AccessRoleKey = (typeof ACCESS_ROLE_KEYS)[number];",
            "export type BuiltinHumanRoleKey = " + " | ".join(ts(r) for r in HUMAN_ROLES) + ";",
            'export type PermissionScope = "org" | "project";', "",
            "export interface PermissionMeta {", "  readonly key: Permission;", "  readonly title: string;",
            "  readonly description: string;", "  readonly category: string;",
            "  readonly roles: readonly AccessRoleKey[];", "  readonly scope: PermissionScope;",
            "  readonly stepUp: boolean;", "  readonly delegable: boolean;", "  readonly critical: boolean;",
            "  readonly systemOnly: boolean;", "}", "",
            "export const PERMISSION_META: Readonly<Record<Permission, PermissionMeta>> = {"]
    for p in c.permissions:
        out.append(
            f'  "{p.key}": {{ key: "{p.key}", title: {ts(p.title)}, description: {ts(p.description)}, '
            f"category: {ts(p.category)}, roles: {ts(list(p.roles))}, scope: {ts(p.scope)}, "
            f"stepUp: {ts(p.step_up)}, delegable: {ts(p.delegable)}, critical: {ts(p.critical)}, "
            f"systemOnly: {ts(p.system_only)} }},"
        )
    out += ["};", "", "export const ROLE_PERMISSIONS: Readonly<Record<AccessRoleKey, readonly Permission[]>> = {"]
    for r in c.roles:
        out.append(f"  {ts(r.key)}: {ts(list(c.role_permissions(r.key)))},")
    out += ["};", "", "const PERMISSION_SET: ReadonlySet<string> = new Set(PERMISSIONS);", "",
            "/** Narrow a string from the wire to a Permission; false for anything the catalogue lacks. */",
            "export function isPermission(value: string): value is Permission {",
            "  return PERMISSION_SET.has(value);", "}", ""]
    return "\n".join(out)


# ---- SQL seed -------------------------------------------------------------------------------------

def _q(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, (list, tuple)):
        return "ARRAY[" + ", ".join(_q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def render_sql(c: Catalogue) -> str:
    out = [f"-- {HEADER}",
           "-- Applied by boss_engine.db.ensure_schema right after db/schema.sql, every boot. Idempotent.",
           "-- Built-in access roles are read-only (org_id NULL, builtin true); their permission rows are",
           "-- reset to exactly the catalogue's. A permission dropped from the catalogue stays in",
           "-- identity_permissions until the migration stream retires it with an audit event (S5).", "",
           "INSERT INTO identity_permissions (key, resource, action, title, description, category, scope_kind,",
           "  step_up, delegable, critical, system_only, readonly_post, catalogue_version) VALUES"]
    rows = []
    for p in c.permissions:
        rows.append("  (" + ", ".join(_q(v) for v in (
            p.key, p.resource, p.action, p.title, p.description, p.category, p.scope, p.step_up,
            p.delegable, p.critical, p.system_only, p.readonly_post, c.version)) + ")")
    out.append(",\n".join(rows))
    out += ["ON CONFLICT (key) DO UPDATE SET resource = EXCLUDED.resource, action = EXCLUDED.action,",
            "  title = EXCLUDED.title, description = EXCLUDED.description, category = EXCLUDED.category,",
            "  scope_kind = EXCLUDED.scope_kind, step_up = EXCLUDED.step_up, delegable = EXCLUDED.delegable,",
            "  critical = EXCLUDED.critical, system_only = EXCLUDED.system_only,",
            "  readonly_post = EXCLUDED.readonly_post, catalogue_version = EXCLUDED.catalogue_version;", "",
            "INSERT INTO identity_access_roles (id, org_id, key, name, description, builtin, system,",
            "  bindable_scopes, mfa_required, version) VALUES"]
    rows = []
    for r in c.roles:
        rows.append("  (" + _q(builtin_role_id(r.key)) + ", NULL, " + ", ".join(_q(v) for v in (
            r.key, r.name, r.description, True, r.system, list(r.bindable_scopes), r.mfa_required,
            c.version)) + ")")
    out.append(",\n".join(rows))
    out += ["ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description,",
            "  builtin = true, system = EXCLUDED.system, bindable_scopes = EXCLUDED.bindable_scopes,",
            "  mfa_required = EXCLUDED.mfa_required, version = EXCLUDED.version;", ""]
    pairs = [(builtin_role_id(r.key), k) for r in c.roles for k in c.role_permissions(r.key)]
    ids = ", ".join(_q(builtin_role_id(r.key)) for r in c.roles)
    values = ",\n".join(f"  ({_q(a)}, {_q(b)})" for a, b in pairs)
    out += [f"DELETE FROM identity_access_role_permissions WHERE role_id IN ({ids})",
            "  AND (role_id, permission_key) NOT IN (VALUES", values + ");", "",
            "INSERT INTO identity_access_role_permissions (role_id, permission_key) VALUES",
            values, "ON CONFLICT DO NOTHING;", ""]
    return "\n".join(out)


# ---- docs -------------------------------------------------------------------------------------------

def render_docs(c: Catalogue) -> str:
    counts = {r: len(c.role_permissions(r)) for r in HUMAN_ROLES}
    system_only = sum(1 for p in c.permissions if p.system_only)
    out = ["# BOSS Identity: the permission catalogue (generated)", "",
           f"<!-- {HEADER} -->", "",
           f"Catalogue version {c.version}, fingerprint `{fingerprint(c)}`. Source: "
           "`packages/identity/catalogue.yaml`. Spec: [IDENTITY.md](IDENTITY.md) §6.", "",
           f"**Totals:** {len(c.permissions)} permissions. "
           + ", ".join(f"{r.title()} holds {counts[r]}" for r in HUMAN_ROLES)
           + f". {system_only} are system-only.", "",
           "Role letters: O Owner, A Admin, P Operator, V Viewer, U Auditor. Flags: step-up, delegable, "
           "org (org-only), system (system-only), critical.", ""]
    category = None
    for p in c.permissions:
        if p.category != category:
            category = p.category
            out += ["", f"## {category}", "", "| Permission | What it allows | O | A | P | V | U | Flags |",
                    "|---|---|:-:|:-:|:-:|:-:|:-:|---|"]
        marks = " | ".join("●" if r in p.roles else " " for r in HUMAN_ROLES)
        flags = [n for n, on in (("step-up", p.step_up), ("delegable", p.delegable),
                                  ("org", p.scope == "org"), ("system", p.system_only),
                                  ("critical", p.critical)) if on]
        sys_roles = [r for r in p.roles if r in SYSTEM_ROLES]
        if sys_roles:
            flags.append("held by " + ", ".join(sys_roles))
        out.append(f"| `{p.key}` | {p.description} | {marks} | {', '.join(flags)} |")
    out += ["", "## Built-in access roles", "", "| Role | Key | Bindable at | MFA required | Holds |",
            "|---|---|---|---|---|"]
    for r in c.roles:
        out.append(f"| {r.name} | `{r.key}` | {', '.join(r.bindable_scopes)} | "
                   f"{'yes' if r.mfa_required else ('n/a' if r.system else 'policy')} | "
                   f"{len(c.role_permissions(r.key))} |")
    out += ["", "## Agent Passport ceiling presets", "", "| Preset | Seeded agents | Permissions | External ceiling |",
            "|---|---|---|---|"]
    for s in c.presets:
        out.append(f"| {s.name} (`{s.key}`) | {', '.join(s.agents)} | "
                   f"{', '.join('`' + k + '`' for k in s.permissions)} | "
                   f"`{json.dumps(dict(s.external_ceiling), sort_keys=True)}` |")
    out.append("")
    return "\n".join(out)


RENDERERS = {"python": render_python, "typescript": render_typescript, "sql": render_sql,
             "docs": render_docs}


def render_all(c: Catalogue | None = None) -> dict[Path, str]:
    catalogue = c or load()
    return {OUTPUTS[name]: fn(catalogue) for name, fn in RENDERERS.items()}


def stale(root: Path | None = None) -> list[Path]:
    base = root or repo_root()
    return [rel for rel, text in render_all().items()
            if not (base / rel).exists() or (base / rel).read_text(encoding="utf-8") != text]


def main(argv: list[str]) -> int:
    base = repo_root()
    if "--check" in argv:
        bad = stale(base)
        for rel in bad:
            print(f"stale: {rel}")
        return 1 if bad else 0
    for rel, text in render_all().items():
        path = base / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
